#!/usr/bin/env bash
set -Eeuo pipefail
export LC_ALL=C

readonly SYSCTL_FILE=/etc/sysctl.d/99-ssh-one-bbr.conf
readonly MODULES_FILE=/etc/modules-load.d/ssh-one-bbr.conf
readonly STATE_DIR=/etc/ssh-one/bbr
readonly STATE_FILE=$STATE_DIR/state
readonly MARKER='# Managed by SSH-one BBR manager. Do not edit this file.'

fail() { printf 'BBR manager: %s\n' "$*" >&2; return 1; }
say() { printf '%s\n' "$*"; }

require_root() {
  [[ ${EUID:-$(id -u)} -eq 0 ]] || { fail 'run this command as root.'; return 1; }
}

require_supported_os() {
  [[ -r /etc/os-release ]] || { fail 'cannot identify the operating system.'; return 1; }
  # shellcheck source=/etc/os-release
  . /etc/os-release
  [[ ${ID:-} == ubuntu && ${VERSION_ID:-} == 20.04 ]] || {
    fail 'this BBR manager only supports Ubuntu 20.04.'
    return 1
  }
  local installed_version
  if [[ ! -r /etc/ssh-one/installation-complete ]]; then
    fail 'SSH-one v30 or newer must be installed before using BBR management.'
    return 1
  fi
  installed_version=$(tr -d '\r\n' < /etc/ssh-one/installation-complete)
  [[ $installed_version =~ ^v[0-9]+$ ]] && (( ${installed_version#v} >= 30 )) || {
    fail "BBR management requires SSH-one v30 or newer; detected ${installed_version:-unknown}."
    return 1
  }
  local architecture
  architecture=$(dpkg --print-architecture 2>/dev/null || true)
  [[ $architecture == amd64 ]] || {
    fail "Ubuntu 20.04 amd64 is required; detected architecture: ${architecture:-unknown}."
    return 1
  }
}

warn_support_lifecycle() {
  say 'Notice: Ubuntu 20.04 standard support ended on 2025-05-31.'
  say 'Kernel updates after that date depend on the configured Ubuntu Pro/ESM or archive sources.'
}

read_sysctl() { sysctl -n "$1" 2>/dev/null || true; }
available_algorithms() { read_sysctl net.ipv4.tcp_available_congestion_control; }

algorithm_available() {
  local wanted=$1 choices
  choices=$(available_algorithms)
  [[ " $choices " == *" $wanted "* ]]
}

managed_path_is_safe() {
  local path=$1
  local -a lines=()
  if [[ -L $path || ( -e $path && ! -f $path ) ]]; then
    fail "refusing to replace a non-regular file or symlink: $path"
    return 1
  fi
  if [[ -f $path ]] && ! grep -Fqx "$MARKER" "$path"; then
    fail "an unrelated file already exists at $path; inspect it before continuing."
    return 1
  fi
  if [[ -f $path ]]; then
    [[ -f $STATE_FILE && ! -L $STATE_FILE ]] || {
      fail "managed BBR settings exist without their state file: $path"
      return 1
    }
    if [[ $path == "$SYSCTL_FILE" ]]; then
      mapfile -t lines < "$path"
      (( ${#lines[@]} == 3 )) && [[ ${lines[0]} == "$MARKER" && ${lines[1]} =~ ^net\.ipv4\.tcp_congestion_control[[:space:]]*=[[:space:]]*[A-Za-z0-9_-]+$ && ${lines[2]} =~ ^net\.core\.default_qdisc[[:space:]]*=[[:space:]]*[A-Za-z0-9_-]+$ ]] || {
        fail "the managed sysctl file contains unexpected edits: $path"
        return 1
      }
    elif [[ $path == "$MODULES_FILE" ]]; then
      [[ $(<"$path") == "$MARKER"$'\n'tcp_bbr ]] || {
        fail "the managed module-load file contains unexpected edits: $path"
        return 1
      }
    fi
  fi
}

read_state() {
  local key value
  STATE_ORIGINAL_CC=''
  STATE_ORIGINAL_QDISC=''
  [[ -f $STATE_FILE && ! -L $STATE_FILE ]] || {
    fail 'the saved BBR state file is missing or unsafe.'
    return 1
  }
  while IFS='=' read -r key value; do
    case $key in
      version) [[ $value == 1 ]] || { fail 'unsupported BBR state version.'; return 1; } ;;
      original_congestion) STATE_ORIGINAL_CC=$value ;;
      original_qdisc) STATE_ORIGINAL_QDISC=$value ;;
      '') ;;
      *) fail 'the saved BBR state file contains an unknown field.'; return 1 ;;
    esac
  done < "$STATE_FILE"
  [[ $STATE_ORIGINAL_CC =~ ^[A-Za-z0-9_-]+$ && $STATE_ORIGINAL_QDISC =~ ^[A-Za-z0-9_-]+$ ]] || {
    fail 'the saved BBR state values are invalid.'
    return 1
  }
}

make_temp_file() {
  local directory=$1 prefix=$2
  install -d -m 0755 "$directory" || return 1
  mktemp "$directory/.${prefix}.XXXXXX"
}

write_sysctl_temp() {
  local path=$1 congestion=$2 qdisc=$3
  printf '%s\n' "$MARKER" 'net.ipv4.tcp_congestion_control = '"$congestion" 'net.core.default_qdisc = '"$qdisc" > "$path"
  chmod 0644 "$path"
}

write_state_temp() {
  local path=$1 congestion=$2 qdisc=$3
  printf 'version=1\noriginal_congestion=%s\noriginal_qdisc=%s\n' "$congestion" "$qdisc" > "$path"
  chmod 0600 "$path"
}

restore_managed_file() {
  local path=$1 backup=$2
  if [[ -n $backup && -f $backup && ! -L $backup ]]; then
    mv -fT -- "$backup" "$path"
  else
    rm -f -- "$path"
  fi
}

status() {
  local kernel cc qdisc choices track
  kernel=$(uname -r 2>/dev/null || printf 'unknown')
  cc=$(read_sysctl net.ipv4.tcp_congestion_control)
  qdisc=$(read_sysctl net.core.default_qdisc)
  choices=$(available_algorithms)
  track=$(detect_kernel_track 2>/dev/null || true)
  printf 'Kernel: %s\n' "$kernel"
  printf 'TCP congestion control: %s\n' "${cc:-unknown}"
  printf 'Available algorithms: %s\n' "${choices:-unknown}"
  printf 'Default qdisc: %s\n' "${qdisc:-unknown}"
  if [[ $cc == bbr ]]; then say 'BBR status: ON'; else say 'BBR status: OFF'; fi
  if [[ -n $track ]]; then printf 'Detected Ubuntu kernel track: %s\n' "$track"; else say 'Detected Ubuntu kernel track: unknown'; fi
  if [[ -r $STATE_FILE ]]; then say 'SSH-one BBR settings: managed'; else say 'SSH-one BBR settings: not managed'; fi
}

enable_bbr() {
  local old_cc old_qdisc original_cc original_qdisc state_tmp sysctl_tmp modules_tmp choices state_was_present=0
  local sysctl_backup='' modules_backup=''
  managed_path_is_safe "$SYSCTL_FILE" || return 1
  managed_path_is_safe "$MODULES_FILE" || return 1

  old_cc=$(read_sysctl net.ipv4.tcp_congestion_control)
  old_qdisc=$(read_sysctl net.core.default_qdisc)
  [[ $old_cc =~ ^[A-Za-z0-9_-]+$ && $old_qdisc =~ ^[A-Za-z0-9_-]+$ ]] || {
    fail 'could not read valid current TCP congestion-control and queue-discipline settings.'
    return 1
  }
  if [[ -e $STATE_FILE ]]; then
    read_state || return 1
    original_cc=$STATE_ORIGINAL_CC
    original_qdisc=$STATE_ORIGINAL_QDISC
    state_was_present=1
  else
    original_cc=$old_cc
    original_qdisc=$old_qdisc
  fi

  if ! algorithm_available bbr; then modprobe tcp_bbr >/dev/null 2>&1 || true; fi
  choices=$(available_algorithms)
  if [[ " $choices " != *' bbr '* ]]; then
    fail 'the running kernel does not provide the standard tcp_bbr algorithm. Use “Update Ubuntu kernel” and reboot, then try again.'
    return 1
  fi

  install -d -m 0700 "$STATE_DIR" || { fail 'could not create the protected BBR state directory.'; return 1; }
  sysctl_tmp=$(make_temp_file /etc/sysctl.d ssh-one-bbr) || { fail 'could not stage the sysctl settings.'; return 1; }
  modules_tmp=$(make_temp_file /etc/modules-load.d ssh-one-bbr) || { rm -f -- "$sysctl_tmp"; fail 'could not stage the kernel-module setting.'; return 1; }
  write_sysctl_temp "$sysctl_tmp" bbr fq
  printf '%s\ntcp_bbr\n' "$MARKER" > "$modules_tmp"
  chmod 0644 "$modules_tmp"

  state_tmp=''
  if [[ ! -e $STATE_FILE ]]; then
    state_tmp=$(make_temp_file "$STATE_DIR" state) || { rm -f -- "$sysctl_tmp" "$modules_tmp"; fail 'could not stage the saved BBR state.'; return 1; }
    write_state_temp "$state_tmp" "$original_cc" "$original_qdisc"
  fi
  if [[ -f $SYSCTL_FILE ]]; then
    sysctl_backup=$(make_temp_file /etc/sysctl.d ssh-one-bbr-rollback) || { rm -f -- "$sysctl_tmp" "$modules_tmp" "$state_tmp"; fail 'could not stage a sysctl rollback copy.'; return 1; }
    cp -a -- "$SYSCTL_FILE" "$sysctl_backup" || { rm -f -- "$sysctl_tmp" "$modules_tmp" "$state_tmp" "$sysctl_backup"; fail 'could not save a sysctl rollback copy.'; return 1; }
  fi
  if [[ -f $MODULES_FILE ]]; then
    modules_backup=$(make_temp_file /etc/modules-load.d ssh-one-bbr-rollback) || { rm -f -- "$sysctl_tmp" "$modules_tmp" "$state_tmp" "$sysctl_backup"; fail 'could not stage a module-load rollback copy.'; return 1; }
    cp -a -- "$MODULES_FILE" "$modules_backup" || { rm -f -- "$sysctl_tmp" "$modules_tmp" "$state_tmp" "$sysctl_backup" "$modules_backup"; fail 'could not save a module-load rollback copy.'; return 1; }
  fi

  if ! mv -fT -- "$sysctl_tmp" "$SYSCTL_FILE"; then
    rm -f -- "$sysctl_tmp" "$modules_tmp" "$state_tmp" "$sysctl_backup" "$modules_backup"
    fail 'could not install the managed sysctl setting.'
    return 1
  fi
  if ! mv -fT -- "$modules_tmp" "$MODULES_FILE"; then
    restore_managed_file "$SYSCTL_FILE" "$sysctl_backup"
    rm -f -- "$modules_tmp" "$state_tmp" "$modules_backup"
    fail 'could not install the managed BBR settings.'
    return 1
  fi
  if [[ -n $state_tmp ]] && ! mv -fT -- "$state_tmp" "$STATE_FILE"; then
    restore_managed_file "$SYSCTL_FILE" "$sysctl_backup"
    restore_managed_file "$MODULES_FILE" "$modules_backup"
    rm -f -- "$state_tmp"
    fail 'could not save the original BBR settings.'
    return 1
  fi

  if ! sysctl -w net.core.default_qdisc=fq >/dev/null || ! sysctl -w net.ipv4.tcp_congestion_control=bbr >/dev/null; then
    sysctl -w "net.ipv4.tcp_congestion_control=$old_cc" >/dev/null 2>&1 || true
    sysctl -w "net.core.default_qdisc=$old_qdisc" >/dev/null 2>&1 || true
    restore_managed_file "$SYSCTL_FILE" "$sysctl_backup"
    restore_managed_file "$MODULES_FILE" "$modules_backup"
    [[ $state_was_present == 1 ]] || rm -f -- "$STATE_FILE"
    fail 'the running kernel rejected BBR settings; managed files were rolled back.'
    return 1
  fi
  if [[ $(read_sysctl net.ipv4.tcp_congestion_control) != bbr ]]; then
    sysctl -w "net.ipv4.tcp_congestion_control=$old_cc" >/dev/null 2>&1 || true
    sysctl -w "net.core.default_qdisc=$old_qdisc" >/dev/null 2>&1 || true
    restore_managed_file "$SYSCTL_FILE" "$sysctl_backup"
    restore_managed_file "$MODULES_FILE" "$modules_backup"
    [[ $state_was_present == 1 ]] || rm -f -- "$STATE_FILE"
    fail 'the kernel did not activate BBR. Check for a conflicting sysctl setting.'
    return 1
  fi
  rm -f -- "$sysctl_backup" "$modules_backup"
  say 'Standard kernel BBR is enabled for new TCP connections. Existing connections are unchanged.'
}

disable_bbr() {
  local old_cc old_qdisc fallback restore_qdisc tmp
  managed_path_is_safe "$SYSCTL_FILE" || return 1
  managed_path_is_safe "$MODULES_FILE" || return 1
  old_cc=$(read_sysctl net.ipv4.tcp_congestion_control)
  old_qdisc=$(read_sysctl net.core.default_qdisc)
  fallback=cubic
  restore_qdisc=${old_qdisc:-fq}
  if [[ -e $STATE_FILE ]]; then
    read_state || return 1
    fallback=$STATE_ORIGINAL_CC
    restore_qdisc=$STATE_ORIGINAL_QDISC
    [[ $fallback != bbr ]] || fallback=cubic
  fi
  if ! algorithm_available "$fallback"; then
    algorithm_available cubic && fallback=cubic || fallback=reno
  fi
  algorithm_available "$fallback" || { fail 'the kernel has no available non-BBR fallback algorithm.'; return 1; }
  [[ $restore_qdisc =~ ^[A-Za-z0-9_-]+$ ]] || restore_qdisc=fq

  tmp=$(make_temp_file /etc/sysctl.d ssh-one-bbr) || { fail 'could not stage the BBR-off setting.'; return 1; }
  write_sysctl_temp "$tmp" "$fallback" "$restore_qdisc"
  if ! mv -fT -- "$tmp" "$SYSCTL_FILE"; then rm -f -- "$tmp"; fail 'could not persist the BBR-off setting.'; return 1; fi
  rm -f -- "$MODULES_FILE"
  if ! sysctl -w "net.core.default_qdisc=$restore_qdisc" >/dev/null || ! sysctl -w "net.ipv4.tcp_congestion_control=$fallback" >/dev/null; then
    fail 'could not apply the BBR-off setting at runtime; the persistent fallback remains in place.'
    return 1
  fi
  printf 'BBR is disabled. TCP congestion control is now %s; the setting persists after reboot.\n' "$fallback"
}

package_installed() {
  [[ $(dpkg-query -W -f='${db:Status-Status}' "$1" 2>/dev/null || true) == installed ]]
}

detect_kernel_track() {
  local kernel
  kernel=$(uname -r 2>/dev/null || true)
  case $kernel in
    *-aws) package_installed linux-aws && { printf '%s' linux-aws; return 0; } ;;
    *-azure) package_installed linux-azure && { printf '%s' linux-azure; return 0; } ;;
    *-gcp) package_installed linux-gcp && { printf '%s' linux-gcp; return 0; } ;;
    *-oracle) package_installed linux-oracle && { printf '%s' linux-oracle; return 0; } ;;
    *-kvm) package_installed linux-kvm && { printf '%s' linux-kvm; return 0; } ;;
    *-virtual) package_installed linux-virtual && { printf '%s' linux-virtual; return 0; } ;;
    *-generic)
      package_installed linux-generic-hwe-20.04 && { printf '%s' linux-generic-hwe-20.04; return 0; }
      package_installed linux-generic && { printf '%s' linux-generic; return 0; }
      package_installed linux-virtual && { printf '%s' linux-virtual; return 0; }
      ;;
  esac
  return 1
}

apt_candidate() {
  apt-cache policy "$1" 2>/dev/null | awk '$1 == "Candidate:" { print $2; exit }'
}

is_official_ubuntu_candidate() {
  local package=$1 candidate=$2 policy
  policy=$(apt-cache policy "$package" 2>/dev/null) || return 1
  printf '%s\n' "$policy" | awk -v wanted="$candidate" '
    /Version table:/ { in_table=1; next }
    in_table && /^[[:space:]]+(\*\*\*[[:space:]]+)?[0-9][^[:space:]]*\.[^[:space:]]*/ {
      line=$0
      sub(/^[[:space:]]+/, "", line)
      sub(/^\*+/, "", line)
      sub(/^[[:space:]]+/, "", line)
      split(line, fields, /[[:space:]]+/)
      current=(fields[1] == wanted)
      next
    }
    in_table && current && /release .*o=Ubuntu(ESM[^, ]*)?([, ]|$)/ { found=1 }
    END { exit !found }
  '
}

install_kernel_track() {
  local package=$1 candidate simulation
  candidate=$(apt_candidate "$package")
  [[ -n $candidate && $candidate != '(none)' ]] || { fail "Ubuntu APT has no candidate version for $package."; return 1; }
  is_official_ubuntu_candidate "$package" "$candidate" || {
    fail "candidate $candidate for $package is not identified as an official Ubuntu/ESM package; refusing it."
    return 1
  }
  say "Official Ubuntu candidate: $package $candidate"
  simulation=$(apt-get -s install --no-install-recommends "$package" 2>&1) || {
    printf '%s\n' "$simulation"
    fail 'APT could not resolve this kernel update.'
    return 1
  }
  printf '%s\n' "$simulation"
  if printf '%s\n' "$simulation" | grep -Eq '^Remv[[:space:]]'; then
    fail 'the proposed kernel update would remove packages; nothing was installed.'
    return 1
  fi
  printf 'Install/update this kernel track using signed Ubuntu APT packages? [y/N] '
  local answer
  IFS= read -r answer || return 1
  [[ $answer == [yY] || $answer == [yY][eE][sS] ]] || { say 'Cancelled; no kernel packages were changed.'; return 0; }
  if ! DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends "$package"; then
    fail 'APT did not complete the kernel update. No kernel packages were purged by SSH-one.'
    return 1
  fi
  say 'Kernel package update completed. Reboot during a maintenance window, then verify uname -r and BBR status.'
  say 'SSH-one did not remove older kernels, change bootloader settings, or reboot the VPS; a provider may select a different kernel.'
}

update_kernel_menu() {
  local track candidate choice
  require_supported_os || return 1
  warn_support_lifecycle
  command -v apt-get >/dev/null && command -v apt-cache >/dev/null || { fail 'APT tools are unavailable.'; return 1; }
  say 'Refreshing package metadata from the configured Ubuntu repositories...'
  apt-get update || { fail 'APT metadata refresh failed; no kernel package was installed.'; return 1; }
  track=$(detect_kernel_track 2>/dev/null || true)
  if [[ -n $track ]]; then
    candidate=$(apt_candidate "$track")
    if [[ -n $candidate && $candidate != '(none)' ]] && is_official_ubuntu_candidate "$track" "$candidate"; then
      printf '\nMatched the running kernel to Ubuntu track %s (official candidate %s)\n' "$track" "$candidate"
      say '1. Update the matching Ubuntu/provider kernel track [recommended; boot compatibility is not guaranteed]'
      if [[ $track != linux-generic ]]; then
        say '2. Install latest Ubuntu generic kernel [APT resolves dependencies; VPS compatibility is unverified]'
      fi
      say '0. Cancel'
      printf 'Select an option: '
      IFS= read -r choice || return 0
      case $choice in
        1) install_kernel_track "$track" ;;
        2)
          [[ $track != linux-generic ]] || { say 'Invalid option.'; return 0; }
          say 'Warning: switching kernel tracks can affect boot or provider-specific drivers. The current kernel will not be purged.'
          install_kernel_track linux-generic
          ;;
        0|'') say 'Cancelled.' ;;
        *) say 'Invalid option.' ;;
      esac
      return
    fi
    printf 'The detected track %s has no verified official Ubuntu candidate.\n' "$track"
  else
    printf 'Could not match running kernel %s to an installed Ubuntu kernel metapackage.\n' "$(uname -r)"
  fi
  say 'No compatible track was verified. The safe choice is to cancel and check Ubuntu repositories/provider kernel support.'
  say '1. Install latest official Ubuntu generic kernel [APT resolves dependencies; VPS compatibility is unverified]'
  say '0. Cancel without changes [recommended]'
  printf 'Select an option: '
  IFS= read -r choice || return 0
  case $choice in
    1)
      say 'Warning: this changes the kernel track and may affect boot or provider-specific drivers. The old kernel is retained, but compatibility is not guaranteed.'
      install_kernel_track linux-generic
      ;;
    0|'') say 'Cancelled.' ;;
    *) say 'Invalid option.' ;;
  esac
}

check_and_install() {
  require_supported_os || return 1
  if algorithm_available bbr; then
    enable_bbr
    return $?
  fi
  modprobe tcp_bbr >/dev/null 2>&1 || true
  if algorithm_available bbr; then
    enable_bbr
    return $?
  fi
  say 'The running kernel does not currently expose standard BBR.'
  say 'Choose the detected compatible Ubuntu kernel track in the update menu, install it, reboot, then retry this option.'
  update_kernel_menu
}

main() {
  require_root || exit 1
  case ${1:-} in
    --status) status; exit 0 ;;
    --enable) require_supported_os && enable_bbr; exit $? ;;
    --disable) require_supported_os && disable_bbr; exit $? ;;
    --update) update_kernel_menu; exit $? ;;
    --install) check_and_install; exit $? ;;
    '') ;;
    *) fail 'unknown argument.'; exit 2 ;;
  esac

  while true; do
    printf '\n%s\n' 'SSH-one BBR MANAGER' '----------------------------------------'
    printf '%s\n' '1. Check and install standard BBR'
    printf '%s\n' '2. Update Ubuntu kernel / BBR'
    printf '%s\n' '3. Enable BBR'
    printf '%s\n' '4. Disable BBR'
    printf '%s\n' '5. Check BBR status'
    printf '%s\n' '0. Back'
    printf '%s' 'Select an option: '
    local choice
    IFS= read -r choice || return 0
    case $choice in
      1) check_and_install || true ;;
      2) update_kernel_menu || true ;;
      3) require_supported_os && enable_bbr || true ;;
      4) require_supported_os && disable_bbr || true ;;
      5) status ;;
      0|'') return 0 ;;
      *) say 'Invalid option.' ;;
    esac
  done
}

main "$@"
